#!/usr/bin/env node
/**
 * Regenerate the template index shipped with the infographic engine reference.
 *
 *   node scripts/sync-engine-indexes.mjs [--check]
 *
 * Source of truth is the installed `@antv/infographic` package, not the repo dossier:
 * the bundle registers every template key with a `design.structure`, while item-node
 * types register a design without a structure — that is what separates the two.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'documd-visuals', 'engines', 'infographic-templates.tsv');
const PKG = path.join(ROOT, '..', 'node_modules', '@antv', 'infographic');

const version = JSON.parse(fs.readFileSync(path.join(PKG, 'package.json'), 'utf8')).version;
const tplDir = path.join(PKG, 'esm', 'templates');
const modules = ['built-in.js', ...fs.readdirSync(tplDir).filter((f) => f.endsWith('.js') && f !== 'built-in.js'
  && !['index.js', 'registry.js', 'utils.js', 'types.js'].includes(f))];
const src = modules.map((f) => fs.readFileSync(path.join(tplDir, f), 'utf8')).join('\n');

/** Extract the item types declared inside the template's own `items: [...]` array. */
function itemStyles(seg) {
  const start = seg.indexOf('items:');
  if (start < 0) return '';
  const open = seg.indexOf('[', start);
  if (open < 0) return '';
  let depth = 0;
  let end = open;
  for (let i = open; i < seg.length; i++) {
    if (seg[i] === '[') depth++;
    else if (seg[i] === ']' && --depth === 0) { end = i; break; }
  }
  return [...new Set([...seg.slice(open, end).matchAll(/type:\s*'([^']+)'/g)].map((m) => m[1]))].join(',');
}

const keys = [...new Set([...src.matchAll(/'([a-z0-9][a-z0-9-]+)':\s*\{/g)].map((m) => m[1]))];
const rows = [];
for (const key of keys) {
  const i = src.indexOf(`'${key}': {`);
  const seg = src.slice(i, i + 1200);
  if (!seg.includes('design:')) continue;          // not a design entry
  const structure = seg.match(/structure:\s*(?:\{\s*type:\s*)?'([^']+)'/);
  if (!structure) continue;                        // item or theme entry, not a template
  rows.push([key, structure[1], itemStyles(seg)]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

const header =
  `# template\tstructure\titem-style(s)\n` +
  `# generated by scripts/sync-engine-indexes.mjs from @antv/infographic ${version} (esm/templates/*.js)\n` +
  `# ${rows.length} templates\n`;
const out = header + rows.map((r) => r.join('\t')).join('\n') + '\n';

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (process.argv.includes('--check')) {
  if (current !== out) {
    console.error(`✗ ${path.relative(ROOT, OUT)} is stale (${rows.length} templates expected)`);
    process.exit(1);
  }
  console.log(`✓ template index up to date (${rows.length} templates, infographic ${version})`);
} else {
  fs.writeFileSync(OUT, out);
  console.log(`✓ wrote ${path.relative(ROOT, OUT)} — ${rows.length} templates (infographic ${version})`);
}
